"""This script creates a pre-processed dataset from the original TSX COS files.

This HDF5 dataset is composed of 3 splits (test/val/test) that are created using spatial splits.
A file stating which image belongs to which split is required (see `--split-file` argument).
The size of the patches can be specified, default is
256x256. The seed can be set for reproducibility, default is 42.
Validation and test sets will include ground truth references generated by ADAM-NOC and MERLIN.

Preprocessing of the images includes:
  - Loading the .cos files
  - Symmetrization
  - Patch extraction (non-overlapping)
  - For validation and test sets, run ADAM-NOC and MERLIN to generate ground truth references
  - Saving the patches in HDF5 files, with shuffling for the training set.

Example usage (from repo root): $ python scripts/dataset/create_dataset.py --input-dir
data/TSX_cos_files --output-dir data/processed_hdf5/ --split-file
data/TSX_cos_files/spatial_splits_5.json
"""

import argparse
import gc
import json
import logging
import sys
from datetime import datetime
from pathlib import Path

import h5py
import hydra
import numpy as np
import torch
from omegaconf import OmegaConf
from tqdm import tqdm

sys.path.append(str(Path(__file__).resolve().parent.parent.parent))
from src.models.merlin_module import MerlinModule
from src.models.sar_ddc_module import SARDDCModule
from src.utils.constants import AMP_MAX, AMP_MIN
from src.utils.processing_utils import extract_short_name_from_TSX_filepath
from src.utils.sar_utils import (
    extract_patches,
    load_cosar,
    symmetrize,
)


class Colors:
    """ANSI color codes for console output."""

    RED = "\033[31m"
    YELLOW = "\033[33m"
    GREEN = "\033[32m"
    BLUE = "\033[34m"
    RESET = "\033[0m"


NB_GTS = 2  # Number of ground truths to store per patch: ADAM-NOC and MERLIN
ADAM_NOC_CKPT_PATH = Path("data/method_ground_truths/ADAM_NOC/checkpoints/last.ckpt")
MERLIN_CKPT_PATH = Path("data/method_ground_truths/MERLIN/checkpoints/last.ckpt")


# Parse command-line arguments
parser = argparse.ArgumentParser(description="Process SAR .cos files and create HDF5 datasets.")
parser.add_argument("--input-dir", type=str, required=True, help="Directory containing .cos files")
parser.add_argument("--output-dir", type=str, required=True, help="Directory to save HDF5 files")
parser.add_argument(
    "--split-file",
    type=str,
    required=True,
    help="Path of the split file (JSON format).",
)
parser.add_argument(
    "--patch-size",
    type=int,
    default=256,
    help="Size of patches to extract. Size under 128 not recommended because of MS-SSIM. (default: 256)",
)
parser.add_argument(
    "--seed",
    type=int,
    default=42,
    help="Random seed for reproducibility (default: 42)",
)
args = parser.parse_args()


def setup_logging(output_dir: Path, dataset_name: str):
    """Setup logging to file and console."""
    logger = logging.getLogger(__name__)
    logger.setLevel(logging.INFO)
    # Clear any existing handlers
    for handler in logger.handlers[:]:
        logger.removeHandler(handler)
    # File handler
    log_dir = output_dir / dataset_name
    log_dir.mkdir(parents=True, exist_ok=True)
    log_file = log_dir / "dataset_creation.log"
    file_handler = logging.FileHandler(log_file)
    file_format = logging.Formatter("%(asctime)s - %(levelname)s - %(message)s")
    file_handler.setFormatter(file_format)
    logger.addHandler(file_handler)
    # Console handler
    console_handler = logging.StreamHandler()
    console_format = logging.Formatter("%(message)s")
    console_handler.setFormatter(console_format)
    logger.addHandler(console_handler)
    # Create RankedLogger AFTER setting up root logger
    global log
    log = logger
    log.info(f"Logging configured. Log file: {log_file}")


def _checkpoint_run_dir(ckpt_path: Path) -> Path:
    """Get the run directory from the checkpoint path: .../runs/<date>/checkpoints/<file>.ckpt -> parent.parent"""
    return ckpt_path.parent.parent


def _load_training_cfg_from_ckpt(ckpt_path: Path):
    """Load the original training config from the checkpoint's run directory."""
    run_dir = _checkpoint_run_dir(ckpt_path)
    training_config_path = run_dir / ".hydra" / "config.yaml"
    if not training_config_path.exists():
        raise FileNotFoundError(f"Training config not found at {training_config_path}.")
    log.info(f"Loading original training config from {training_config_path}")
    return OmegaConf.load(training_config_path)


def _instantiate_model_and_load_weights(train_cfg, ckpt_path: Path) -> torch.nn.Module:
    """Instantiate model from Hydra cfg and load weights."""
    log.info(f"Instantiating model <{train_cfg.model._target_}>")
    model = hydra.utils.instantiate(train_cfg.model)
    checkpoint = torch.load(str(ckpt_path), map_location="cpu")
    msg = model.load_state_dict(checkpoint["state_dict"], strict=True)
    log.info(f"Loaded checkpoint state_dict with message: {msg}")
    model.eval()
    return model


@torch.no_grad()
def _predict_linA(model: torch.nn.Module, batch: torch.Tensor) -> torch.Tensor:
    """Run model on batches of normalized real/imag and return linear amplitude reconstructions.

    Inputs:
      - model: SARDDCModule or MerlinModule.
      - batch: tensor [B,2,H,W] normalized in model domain.
    Returns:
      - recon_amp: tensor [B,1,H,W] in linear amplitude domain.
    """
    if isinstance(model, SARDDCModule):
        # ADAM forward passes in evaluation takes input with 2 channels
        output = model(batch)
        recon_real = output["x_hat"][:, 0, :, :]  # [B,H,W]
        recon_imag = output["x_hat"][:, 1, :, :]
    elif isinstance(model, MerlinModule):
        # While MERLIN takes one channel at a time
        recon_real = model(batch[:, 0:1, :, :])
        recon_imag = model(batch[:, 1:2, :, :])
        recon_real = recon_real[:, 0, :, :]
        recon_imag = recon_imag[:, 0, :, :]
    # Type guard for linters
    assert isinstance(
        recon_real, torch.Tensor
    ), "Model output must be a Tensor or dict with 'x_hat'"
    assert isinstance(
        recon_imag, torch.Tensor
    ), "Model output must be a Tensor or dict with 'x_hat'"

    # Denormalize, average, return linear amplitude
    recon_real_lin = torch.exp(recon_real * (AMP_MAX - AMP_MIN) + AMP_MIN)
    recon_imag_lin = torch.exp(recon_imag * (AMP_MAX - AMP_MIN) + AMP_MIN)
    recon_linA = torch.sqrt(
        0.5 * (torch.square(recon_real_lin) + torch.square(recon_imag_lin))
    )  # [B,H,W]
    return recon_linA


def add_metadata_to_dataset(
    dset: h5py.Dataset,
    nb_patches: int,
    patches_per_image: dict[str, int],
):
    """Add metadata to the shuffled dataset."""
    dset.attrs["creation_date"] = datetime.now().isoformat()
    dset.attrs["seed"] = args.seed
    dset.attrs["split_file"] = args.split_file
    dset.attrs["patch_size"] = args.patch_size
    dset.attrs["nb_patches"] = nb_patches
    dset.attrs["patches_per_image"] = "_".join(
        f"{name}-{count}" for name, count in patches_per_image.items()
    )  # e.g., "Roma-123_Geneva-456"

    log.info(f"Metadata added to dataset: {dset.attrs}.")


def process_dataset(
    filenames: dict[str, list[Path]],
    output_dir: Path,
):
    """Process the dataset: load images, symmetrize, patchify, and save to HDF5 files."""
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    log.info(f"Using device: {device}")

    # Load both models once
    if not ADAM_NOC_CKPT_PATH.exists():
        raise FileNotFoundError(f"ADAM-NOC checkpoint not found at {ADAM_NOC_CKPT_PATH}")
    if not MERLIN_CKPT_PATH.exists():
        raise FileNotFoundError(f"MERLIN checkpoint not found at {MERLIN_CKPT_PATH}")

    adam_cfg = _load_training_cfg_from_ckpt(ADAM_NOC_CKPT_PATH)
    merlin_cfg = _load_training_cfg_from_ckpt(MERLIN_CKPT_PATH)

    adam_model = _instantiate_model_and_load_weights(adam_cfg, ADAM_NOC_CKPT_PATH).to(device)
    merlin_model = _instantiate_model_and_load_weights(merlin_cfg, MERLIN_CKPT_PATH).to(device)
    # ----------------------------------------------------
    # ---- Manage training files (chunked processing) ----
    # ----------------------------------------------------
    log.info(
        f"{Colors.YELLOW}Processing training split with {len(filenames['train'])} files.{Colors.RESET}"
    )
    nb_patches_split = {}
    with h5py.File(output_dir / "unshuffled.h5", "w") as f:
        hdf5_dataset = f.create_dataset(
            "patches",
            shape=(0, args.patch_size, args.patch_size, 2),
            maxshape=(None, args.patch_size, args.patch_size, 2),
            dtype="float32",
            chunks=True,
        )

        patches_per_image = {}
        for i, file_path in enumerate(filenames["train"]):
            short_name = extract_short_name_from_TSX_filepath(file_path)
            log.info(
                f" - {Colors.BLUE}Processing {i + 1}/{len(filenames['train'])}: {short_name}{Colors.RESET}"
            )
            # Load, symmetrize, patchify
            image = load_cosar(file_path, logger=log)
            if image is None:
                raise ValueError(f"Failed to load {file_path}")
            image = symmetrize(image)
            patches = extract_patches(image, args.patch_size, stride=args.patch_size)
            del image

            nb_patches = patches.shape[0]
            patches_per_image[short_name] = nb_patches
            log.info(f"      Extracted {nb_patches} patches from {short_name}.")
            hdf5_dataset.resize(hdf5_dataset.shape[0] + nb_patches, axis=0)
            hdf5_dataset[-nb_patches:] = patches

            del patches
    gc.collect()

    # Out-of-core shuffle
    log.info("Shuffling training patches...")
    with h5py.File(output_dir / "unshuffled.h5", "r") as f:
        patches_dataset = f["patches"]
        nb_patches_split["training"] = patches_dataset.shape[0]
        # Create a random permutation of indices
        indices = np.random.permutation(nb_patches_split["training"])

        with h5py.File(output_dir / "train.h5", "w") as out_f:
            shuffled_dataset = out_f.create_dataset(
                "patches",
                shape=(
                    nb_patches_split["training"],
                    args.patch_size,
                    args.patch_size,
                    2,
                ),
                dtype="float32",
            )
            chunk_size = 1024
            for i in range(0, nb_patches_split["training"], chunk_size):
                batch_indices = indices[i : i + chunk_size]
                # Read patches in original order
                tmp_data = patches_dataset[batch_indices.min() : batch_indices.max() + 1]
                # Map to the shuffled order
                remapped_indices = batch_indices - batch_indices.min()
                # Write to output in shuffled order
                shuffled_dataset[i : i + len(batch_indices)] = tmp_data[remapped_indices]

            add_metadata_to_dataset(
                shuffled_dataset,
                nb_patches_split["training"],
                patches_per_image,
            )
        log.info(
            f"Saved {nb_patches_split['training']} shuffled training patches to {output_dir / 'train.h5'}"
        )

    (output_dir / "unshuffled.h5").unlink(missing_ok=True)

    # -------------------------------------------------------
    # ---- Manage validation and testing files (add GTs) ----
    # -------------------------------------------------------
    # For validation and training no need to chunk the processing, as they should only contain one image each.

    for split in ["val", "test"]:
        log.info(
            f"{Colors.YELLOW}Processing {split} split with {len(filenames[split])} files.{Colors.RESET}"
        )

        patches_per_image: dict[str, int] = {}
        per_file_patches: list[np.ndarray] = []
        total_patches = 0

        for i, file_path in enumerate(filenames[split]):
            short_name = extract_short_name_from_TSX_filepath(file_path)
            log.info(f"  - {Colors.BLUE}Processing {short_name}{Colors.RESET}")

            # Load, symmetrize, patchify
            image = load_cosar(file_path, logger=log)
            if image is None:
                raise ValueError(f"Failed to load {file_path}")
            image = symmetrize(image)
            patches = extract_patches(image, args.patch_size, stride=args.patch_size)  # [N,H,W,2]

            nb_patches = int(patches.shape[0])
            patches_per_image[short_name] = nb_patches
            total_patches += nb_patches
            log.info(f"      Extracted {nb_patches} patches from {short_name}.")

            # Prepare outputs for this file
            out_file = np.empty(
                (nb_patches, args.patch_size, args.patch_size, NB_GTS + 2), dtype=np.float32
            )
            # Fill real/imag directly (raw, no normalization)
            out_file[..., 0] = patches[..., 0]
            out_file[..., 1] = patches[..., 1]

            # Batch inference for predictions
            batch_size = 16
            for start in tqdm(
                range(0, nb_patches, batch_size),
                desc=f"Infer {short_name}",
                unit="patch",
                leave=False,
            ):
                end = min(start + batch_size, nb_patches)
                batch = patches[start:end].astype(np.float32)  # [B,H,W,2]
                batch = torch.from_numpy(batch).permute(0, 3, 1, 2).contiguous()  # [B,2,H,W]
                batch = batch.to(device)

                # Predictions (amplitude in linear domain)
                adam_linA = _predict_linA(adam_model, batch)
                merlin_linA = _predict_linA(merlin_model, batch)

                out_file[start:end, :, :, 2] = adam_linA.cpu().numpy()
                out_file[start:end, :, :, 3] = merlin_linA.cpu().numpy()
                # Free GPU memory for large batches
                del batch, adam_linA, merlin_linA
                torch.cuda.empty_cache() if device.type == "cuda" else None

            per_file_patches.append(out_file)
            # Free memory
            del patches, out_file
            gc.collect()

        # Concatenate all patches for this split and save
        patches = np.concatenate(per_file_patches, axis=0)
        nb_patches_split[split] = patches.shape[0]
        del per_file_patches

        with h5py.File(output_dir / f"{split}.h5", "w") as f:
            dset = f.create_dataset(
                "patches",
                data=patches,
                maxshape=(None, args.patch_size, args.patch_size, NB_GTS + 2),
                dtype="float32",
            )
            add_metadata_to_dataset(
                dset,
                int(nb_patches_split[split]),
                patches_per_image,
            )
        del patches
        log.info(
            f"Saved {split} split with {nb_patches_split[split]} patches to {output_dir / f'{split}.h5'}"
        )
        total_nb_patches = sum(nb_patches_split.values())
        log.info(f"In total {total_nb_patches} patches processed:")
        for split in nb_patches_split.keys():
            log.info(f"  - {nb_patches_split[split] / total_nb_patches * 100:.2f}% {split}")


def main():
    """Main function to setup logging, validate arguments, and process the dataset."""
    # ----- Setup logging -----
    input_dir = Path(args.input_dir)
    output_dir = Path(args.output_dir)
    split_file = Path(args.split_file)
    dataset_name = f"TSX_{split_file.stem}_{args.patch_size}x{args.patch_size}"
    setup_logging(output_dir, dataset_name)

    # ----- Validate script arguments -----
    if not input_dir.is_dir():
        raise RuntimeError(f"Input directory does not exist: {input_dir}")
    if not output_dir.is_dir():
        raise RuntimeError(f"Output directory does not exist: {output_dir}")

    # ----- Print configuration -----
    log.info(f"{Colors.YELLOW}TSX Dataset Creation - Configuration:{Colors.RESET}")
    log.info(f"  Input directory: {args.input_dir}")
    log.info(f"  Output directory: {args.output_dir}")
    log.info(f"  Split file: {args.split_file}")
    log.info(f"  Patch size: {args.patch_size}x{args.patch_size}")
    log.info(f"  Seed: {args.seed}")
    log.info("")

    # ----- Determine splits -----
    with open(args.split_file) as f:
        splits = json.load(f)
    filenames = {
        "train": splits.get("train", []),
        "val": splits.get("val", []),
        "test": splits.get("test", []),
    }
    for split, files in filenames.items():
        log.info(f"Files for {split} split:")
        filepaths = []
        for file in files:
            file_path = input_dir / file
            log.info(f"  - {extract_short_name_from_TSX_filepath(file_path)}")
            if not file_path.is_file():
                raise RuntimeError(f"Expected file for {split} split does not exist: {file_path}")
            filepaths.append(file_path)
        filenames[split] = filepaths

    # ----- Set seeds -----
    np.random.seed(args.seed)
    # random.seed(args.seed)
    torch.manual_seed(args.seed)

    # ----- Process -----
    start_time = datetime.now()
    log.info(
        f"{Colors.GREEN}Starting the creation of the dataset {dataset_name} at {start_time}{Colors.RESET}",
    )

    process_dataset(
        filenames,
        output_dir / dataset_name,
    )
    end_time = datetime.now()
    log.info(f"{Colors.GREEN}Processing completed successfully!{Colors.RESET}")
    log.info(
        f"Started: {start_time}. Finished: {end_time}. Total duration: {end_time - start_time}."
    )


if __name__ == "__main__":
    main()
